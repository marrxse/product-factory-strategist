"""Прогноз планового года по пяти строкам таблицы брифа, окупаемость и ресурсы (воспроизводимо).

Факты — таблица брифа (E9–E13, E16, E19). Остальное — допущения агента [ГИП], названные константами.
Два хода событий: основной и менее благоприятный. Запуск: python3 state/analysis/forecast.py
"""
from __future__ import annotations

BAU = {"gp": 279.0, "active": 5000, "conn": 8000, "owners": 1000, "activ": 0.45}   # без изменений (E9–E13)
TARGET = {"gp": 285.0, "active": 8000, "conn": 12000, "owners": 2000, "activ": 0.60}
RATE = 500  # руб. за доп. оплаченный месяц номера (E16)

# [ГИП] допущения: (основной, менее благоприятный)
COMPATIBLE = (0.60, 0.45)        # доля групп на тарифах, где можно выделять интернет из остатка
PERMISSION = (0.50, 0.30)        # участник разрешил показывать остаток
EVENT_GROUP = (0.44, 0.28)       # группа хотя бы раз в месяц получает сигнал (2 участника, 25% / 15% на номер)
ACT_ON_SIGNAL = (0.40, 0.25)     # организатор действует по сигналу
ROLLOUT_SHARE = (1.0, 0.0)       # B — второй шаг: раскатка к декабрю только при эффекте пилота III квартала
INACTIVE_SHARE = 0.375           # доля групп, неактивных без изменений (1 − 5 000 / 8 000)
ACTIV_LIFT = (0.03, -0.02)       # [ГИП] запрос разрешения при создании группы: может поднять активацию или снизить принятие приглашений
GROUP_KEEP = (100, 0)            # группы, не распавшиеся благодаря активности (раскатка с октября)
OWNERS_Q4 = (500, 100)           # [ГИП] владельцы, объединившие номера ради напоминания (раскатка E с июля)
F_NUMBERS = (0, 0)               # тест F не одобрен — в основной прогноз не входит
E_MONEY_MLN = (0.55, 0.05)       # E с июля на доступной базе, owners_access.py версии 2 (E65), до расходов на напоминания
E_REMINDER_COST_MLN = (0.24, 0.15)  # расходы на напоминания за 6 месяцев: 2 СМС в месяц по 1 руб. [ГИП]
F_MONTHS = 2                     # в среднем оплаченных месяцев в плановом году при равномерном притоке с октября
B_RETENTION_MLN = (0.005, 0.0)   # деньги B за 3 месяца (с октября) после замещения допакетов, E42
PM_COST = 0.3                    # млн руб. за человеко-месяц, учебное допущение
PEOPLE_PM = {"разработка (E 0,5 + B 1,5)": 2.0, "тестирование": 1.0, "дизайнер 0,5 × 6 мес.": 3.0, "аналитик 0,5 × 9 мес.": 4.5}


def forecast(i: int) -> dict[str, float]:
    conn = BAU["conn"] + GROUP_KEEP[i]
    reached = ROLLOUT_SHARE[i] * conn * COMPATIBLE[i] * PERMISSION[i] * EVENT_GROUP[i] * ACT_ON_SIGNAL[i]
    active = BAU["active"] + GROUP_KEEP[i] * 0.625 + reached * INACTIVE_SHARE
    gp = BAU["gp"] + B_RETENTION_MLN[i] + F_NUMBERS[i] * F_MONTHS * RATE / 1e6 + E_MONEY_MLN[i] - E_REMINDER_COST_MLN[i]
    return {"gp": gp, "active": active, "conn": conn, "owners": BAU["owners"] + OWNERS_Q4[i],
            "activ": BAU["activ"] + ACTIV_LIFT[i]}


def show(name: str, f: dict[str, float]) -> None:
    print(f"{name}: прибыль {f['gp']:.1f} млн руб. (цель {TARGET["gp"]:.0f} · разрыв {TARGET['gp'] - f['gp']:.1f});"
          f" активные {f['active']:,.0f} (цель {TARGET['active']:,});"
          f" подключённые {f['conn']:,.0f} (цель {TARGET['conn']:,});"
          f" владельцы {f['owners']:,.0f} (цель {TARGET['owners']:,});"
          f" активация {f['activ']:.0%} (цель {TARGET['activ']:.0%})".replace(",", " "))


if __name__ == "__main__":
    show("основной", forecast(0))
    show("менее благоприятный", forecast(1))
    cost = sum(PEOPLE_PM.values()) * PM_COST
    print(f"вложения в пилоты E и B: {sum(PEOPLE_PM.values()):.1f} человеко-месяца × {PM_COST} млн = {cost:.2f} млн руб.")
    yearly = 0.07  # первые 12 месяцев работы B после замещения, E42
    print(f"окупаемость деньгами B (линейная экстраполяция первого года): {cost / yearly:.0f} лет — B окупается не прибылью, а пользой для клиента")
    for horizon in (1, 3):
        print(f"предельные вложения, которые вернутся за {horizon} г. только удержанием: {yearly * horizon:.2f} млн руб.")
    need_f = (TARGET['gp'] - BAU['gp']) * 1e6 / RATE / F_MONTHS
    print(f"чтобы F закрыл разрыв в плановом году: ≈{need_f:,.0f} новых номеров".replace(",", " "))
    for extra in (0, 800, 1500):
        end = 8100 + 2 * (1500 + extra)
        print(f"ориентир конца 3-го года: 8 100 + 2 × (1 500 + {extra}) = {end:,} групп = {end / 1000:.1f}% из 100 000; активных ≥65% = {end * 0.65:,.0f}".replace(",", " "))
    print("второй год: E на полный год — +1,78 млн руб. минус ≈0,48 млн на напоминания = +1,3 млн руб. в базовом сценарии (E65)")
    for owners in (2000, 3000, 4000):
        print(f"ориентир владельцев 2029: {owners} объединивших номера = {owners / 40000:.1%} из 40 000 доступных")
