"""Воронка подключений, цена дополнительного подключения и доход группы за время обслуживания (воспроизводимо).

Факты — таблица брифа (E11, E13) и учебная ставка 500 руб. (E16); пример воронки 100 → 60 → 30 — из брифа (E15).
Остальное — допущения агента [ГИП]. Бриф просит: показать, сколько организаторов создадут группу, в скольких
примут приглашение и в скольких совершат первое действие; цену каждого дополнительного подключения; при нехватке
данных об удержании — условный расчёт дохода группы за время обслуживания по размеру группы.
"""
from __future__ import annotations

START, END_BAU = 6500, 8000          # подключённые группы: начало и конец планового года без изменений (E11)
ACTIVATION_BAU = 0.45                 # активация за 14 дней без изменений (E13)
GROUP_EXIT = (0.15, 0.20, 0.25)       # [ГИП] доля групп, распавшихся за год
ACCEPT = 0.60                         # [ГИП] доля созданных групп, где приняли приглашение (как в примере брифа, E15)
RATE = 500                            # руб. валовой прибыли за оплаченный месяц номера (E16)
MONTHLY_KEEP = (0.97, 0.98, 0.99)     # [ГИП] вероятность, что номер продолжит платить в следующем месяце
CHANNEL_COST = 300_000                # [ГИП] пример расходов на канал за квартал, руб.


def fmt(x: float) -> str:
    return f"{x:,.0f}".replace(",", " ")


def funnel() -> None:
    for exit_rate in GROUP_EXIT:
        exits = START * exit_rate
        new_connected = END_BAU - START + exits
        created = new_connected / ACCEPT
        activated = created * ACTIVATION_BAU
        print(f"воронка без изменений (распад групп {exit_rate:.0%} в год): создано ≈{fmt(created)} групп → приглашение приняли"
              f" ≈{fmt(new_connected)} → первое действие за 14 дней ≈{fmt(activated)}; распалось ≈{fmt(exits)}")
    print("   где люди останавливаются: приглашение без ответа (≈40% созданных) и нет действия после вступления —"
          " поэтому запрос разрешения и первый сигнал стоят в начале пути")


def cost_per_connection() -> None:
    for extra in (50, 100, 200):
        print(f"цена дополнительного подключения: расходы {fmt(CHANNEL_COST)} руб. / прирост {extra} групп к обычному"
              f" обслуживанию = {fmt(CHANNEL_COST / extra)} руб. за группу [ГИП: формула, расходы — пример]")


def lifetime_value() -> None:
    for numbers in (2, 4):
        for keep in MONTHLY_KEEP:
            value = sum(numbers * RATE * keep ** t for t in range(36))
            print(f"доход группы из {numbers} номеров за 36 месяцев при удержании {keep:.0%} в месяц:"
                  f" ≈{value / 1000:.0f} тыс. руб.")
    print("   сравнивать группы одного размера: семья из 4 номеров приносит больше семьи из 2 уже из-за числа номеров")


if __name__ == "__main__":
    funnel()
    cost_per_connection()
    lifetime_value()
