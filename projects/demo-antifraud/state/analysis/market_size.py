"""Объём рынка семейной защиты: TAM → SAM → SOM за первый год и сравнение с точкой окупаемости (воспроизводимо).

Факт — только численность людей старше трудоспособного возраста (E79). Всё остальное — допущения агента [ГИП],
вынесенные в константы, чтобы их можно было заменить данными аудита и интервью:
- HAS_PROTECTOR — у какой доли пожилых есть взрослый близкий, который возьмётся их защищать;
- NET_SHARE — доля пожилых в нашей сети (оператор в демо условный — три масштаба);
- SAME_NET — вероятность, что защищающий тоже в нашей сети (от «независимо» = доле до «семьи у одного оператора»);
- REACH — доля пар из SAM, до которых за год дойдёт приглашение через собственные каналы (платной рекламы нет — C11);
- CONSENT, FIRST_PAY — пороги «продолжить» из плана проверки.
"""
OLDER = 35_100_000                    # старше трудоспособного возраста, начало 2025 (E79)
HAS_PROTECTOR = (0.6, 0.8)            # [ГИП]
NET_SHARE = (0.15, 0.25, 0.30)        # [ГИП] доля нашей сети среди пожилых
SAME_NET = (0.25, 0.50)               # [ГИП]
REACH = (0.05, 0.15)                  # [ГИП] за первый год
CONSENT, FIRST_PAY = 0.40, 0.10       # validation-plan.md
NEED_PER_YEAR = (547 * 12, 2810 * 12)  # новых платящих пар в год для окупаемости (breakeven.py, E49)
PRICE = 149                           # ₽ в месяц за пару — цена пилота


def fmt(x: float) -> str:
    return f"{x:,.0f}".replace(",", " ")


tam = [OLDER * h for h in HAS_PROTECTOR]
print(f"TAM (пары «пожилой близкий + защищающий» по стране): {fmt(tam[0])}–{fmt(tam[1])}")
print(f"нужно новых платящих пар в год для окупаемости: {fmt(NEED_PER_YEAR[0])}–{fmt(NEED_PER_YEAR[1])}")
for share in NET_SHARE:
    sam = (tam[0] * share * SAME_NET[0], tam[1] * share * SAME_NET[1])
    som = (sam[0] * REACH[0] * CONSENT * FIRST_PAY, sam[1] * REACH[1] * CONSENT * FIRST_PAY)
    revenue = [s * PRICE * 12 / 1e6 for s in som]
    cover = "покрывает" if som[0] >= NEED_PER_YEAR[1] else ("может покрыть" if som[1] >= NEED_PER_YEAR[0] else "не покрывает")
    print(f"доля сети {share:.0%}: SAM {fmt(sam[0])}–{fmt(sam[1])} пар; SOM за год {fmt(som[0])}–{fmt(som[1])} платящих пар; "
          f"выручка за год не выше {revenue[0]:.0f}–{revenue[1]:.0f} млн ₽; точку окупаемости {cover}")
