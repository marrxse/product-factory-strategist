"""Сколько пар нужно на каждую цену, чтобы ценовой A/B различил конверсию в оплату.

Входы — допущения агента: конверсия 10% при 149 ₽ (порог «продолжить» из плана проверки)
и 7,5% при 199 ₽ (снижение на четверть при цене выше на треть — гипотеза, данных об эластичности нет).
Двусторонний тест двух долей, уровень значимости 5%, мощность 80%.
"""
import math

Z_ALPHA, Z_BETA = 1.96, 0.8416


def per_group(p1: float, p2: float) -> int:
    variance = p1 * (1 - p1) + p2 * (1 - p2)
    return math.ceil((Z_ALPHA + Z_BETA) ** 2 * variance / (p1 - p2) ** 2)


if __name__ == "__main__":
    for p1, p2 in [(0.10, 0.075), (0.10, 0.06), (0.10, 0.05)]:
        n = per_group(p1, p2)
        print(f"конверсия {p1:.1%} против {p2:.1%}: {n} согласившихся пар на цену, {2 * n} на тест")
    print("в пилоте всего около 400 согласившихся пар (план проверки) — на две цены по 200")
