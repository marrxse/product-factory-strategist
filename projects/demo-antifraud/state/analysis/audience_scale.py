"""Масштаб: сколько защищающих должны отправить приглашение, чтобы семейная защита окупилась (воспроизводимо).

Входы — НЕ данные рынка: точка окупаемости из breakeven.py (модель на допущениях, E49) и пороги «продолжить»
из плана проверки (согласие близких ≥40% приглашений, первая оплата ≥10% согласившихся пар) — оба [ГИП].
Результат — доля абонентской базы, которая должна отправить приглашение за год, для баз разного размера.
"""
NEED_PER_MONTH = (547, 2810)     # новых платящих пар в месяц при бесплатном привлечении и 199 ₽ (вывод breakeven.py)
CONSENT, FIRST_PAY = 0.40, 0.10  # пороги «продолжить» из validation-plan.md
BASES_MLN = (1, 10, 50)          # размер абонентской базы оператора, млн — три масштаба для ориентира

pay_per_invite = CONSENT * FIRST_PAY
year = [n * 12 for n in NEED_PER_MONTH]
invites = [y / pay_per_invite for y in year]
print(f"платящих пар на одно приглашение: {pay_per_invite:.0%}")
print(f"нужно новых платящих пар в год: {year[0]:,}–{year[1]:,}".replace(",", " "))
print(f"нужно приглашений в год: {invites[0]:,.0f}–{invites[1]:,.0f}".replace(",", " "))
for base in BASES_MLN:
    lo, hi = (i / (base * 1_000_000) for i in invites)
    print(f"база {base} млн абонентов: приглашение должны отправить {lo:.1%}–{hi:.1%} абонентов в год")
