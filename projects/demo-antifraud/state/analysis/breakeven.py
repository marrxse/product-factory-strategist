"""Точка безубыточности семейной защиты (воспроизводимо). ВСЕ входы — допущения агента, не данные:
внутренних данных о затратах и оттоке нет (ограничение брифа). Модель показывает, какой масштаб нужен,
чтобы руководитель сравнил его со своими данными после аудита недели 1."""
PRICES = (149, 199)                 # ₽/мес за пару — точки теста из product-strategy.md
MONTHLY_CHURN = (0.10, 0.20)        # отток платящих пар в месяц — допущение
MARGIN = 0.8                        # доля выручки после платёжных и операционных расходов — допущение
INVESTMENT = (3_000_000, 6_000_000, 10_000_000)  # ₽: доработка П2–П3, юристы, пилот, продвижение — сценарии
HORIZON = 12                        # месяцев окупаемости

def lifetime_months(churn: float, horizon: int) -> float:
    """Сумма вероятностей остаться за горизонт: Σ (1-churn)^t, t=0..horizon-1."""
    return sum((1 - churn) ** t for t in range(horizon))

print("инвестиции | цена | отток/мес | пар-новых, которых нужно привлечь за год (при равномерном наборе ~ /12 в месяц)")
for inv in INVESTMENT:
    for price in PRICES:
        for churn in MONTHLY_CHURN:
            value = price * MARGIN * lifetime_months(churn, HORIZON) / 2   # набор равномерный → в среднем полгоризонта
            pairs = inv / value
            print(f"{inv/1e6:.0f} млн ₽ | {price} ₽ | {churn:.0%} | ≈{pairs:,.0f} пар (≈{pairs/12:,.0f} в месяц)".replace(",", " "))
