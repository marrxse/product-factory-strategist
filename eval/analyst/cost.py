"""Сравнение с аналитиком вручную: сколько стоила бы та же работа у человека — воспроизводимый расчёт.

ФАКТЫ — из снимков в eval/analyst/sources/ (ссылки в README). ДОПУЩЕНИЯ — помечены, меняйте и перезапускайте:
python3 eval/analyst/cost.py
"""
# ФАКТ: Хабр Карьера, первое полугодие 2026 — медиана продуктового аналитика и сеньора, ₽ в месяц
SALARY_MEDIAN, SALARY_SENIOR = 238_000, 374_000
# ФАКТ: прайс агентства SDA — кабинетное исследование, экспресс-исследование, стратегия: (цена от, ₽; срок)
AGENCY = (("кабинетное исследование", 220_000, "15–22 дня"), ("экспресс-исследование рынка", 140_000, "до 10 дней"),
          ("разработка стратегии компании", 1_200_000, "4–6 месяцев"))
# ФАКТ: агент на демо, этапы 0–7 — стоимость в ценах API (state/cost.csv) и время по журналу
AGENT_USD, AGENT_MIN, HUMAN_GATES_MIN = 14.87, 28, 10

HOURS_PER_MONTH = 164          # ДОПУЩЕНИЕ: рабочих часов в месяце
EMPLOYER_OVERHEAD = 1.3        # ДОПУЩЕНИЕ: страховые взносы и рабочее место сверх зарплаты
HOURS_PER_DAY = 8              # ДОПУЩЕНИЕ: полный рабочий день на задачу
RUB_PER_USD = (80, 100)        # ДОПУЩЕНИЕ: диапазон курса для перевода цены API в рубли
HUMAN_REVIEW_HOURS = (2, 4)    # ДОПУЩЕНИЕ: руководитель вычитывает результат агента сверх ворот
TASKS = (                      # ДОПУЩЕНИЕ: часы аналитика на тот же объём, что в демо (≈60 записей реестра с цитатами)
    ("постановка задачи и бриф", 2, 4),
    ("сбор источников и реестр с цитатами", 12, 20),
    ("план исследования", 2, 3),
    ("исследование и синтез", 8, 12),
    ("поведение клиентов и расчёт оттока", 6, 10),
    ("разбор интерфейса конкурента", 3, 5),
    ("проверка ответов нейросетей", 2, 3),
    ("варианты, матрица, возражения", 6, 10),
    ("продуктовая стратегия", 6, 8),
    ("коммуникационная стратегия и креатив", 6, 10),
    ("план проверки, экономика, решение на одной странице", 5, 8),
    ("самопроверка и вычитка", 4, 6),
)


def n(x: float) -> str:
    """Число с пробелом между разрядами."""
    return f"{x:,.0f}".replace(",", " ")


def main() -> None:
    low = sum(t[1] for t in TASKS)
    high = sum(t[2] for t in TASKS)
    rate = [s * EMPLOYER_OVERHEAD / HOURS_PER_MONTH for s in (SALARY_MEDIAN, SALARY_SENIOR)]
    print(f"аналитик: {low}–{high} ч ≈ {low / HOURS_PER_DAY:.0f}–{high / HOURS_PER_DAY:.0f} рабочих дней")
    print(f"ставка с налогами: {n(rate[0])} ₽/ч (медиана) … {n(rate[1])} ₽/ч (сеньор)")
    print(f"аналитик, стоимость: {n(low * rate[0])}–{n(high * rate[0])} ₽ (медиана); {n(low * rate[1])}–{n(high * rate[1])} ₽ (сеньор)")
    for name, price, term in AGENCY:
        print(f"агентство, {name}: от {n(price)} ₽, {term}")
    agent_rub = [AGENT_USD * r for r in RUB_PER_USD]
    review_rub = [h * rate[0] for h in HUMAN_REVIEW_HOURS]
    print(f"агент: {AGENT_USD} $ в ценах API ≈ {n(agent_rub[0])}–{n(agent_rub[1])} ₽; "
          f"{AGENT_MIN} мин работы агента + {HUMAN_GATES_MIN} мин решений человека")
    total = [agent_rub[0] + review_rub[0], agent_rub[1] + review_rub[1]]
    print(f"агент + вычитка руководителем {HUMAN_REVIEW_HOURS[0]}–{HUMAN_REVIEW_HOURS[1]} ч: ≈{n(total[0])}–{n(total[1])} ₽ "
          f"(из них модель — {n(agent_rub[0])}–{n(agent_rub[1])} ₽, остальное — время человека)")
    print(f"дешевле аналитика (медиана): в {low * rate[0] / total[1]:.0f}–{high * rate[0] / total[0]:.0f} раз; "
          f"быстрее по календарю: часы против {low / HOURS_PER_DAY:.0f}–{high / HOURS_PER_DAY:.0f} рабочих дней")


if __name__ == "__main__":
    main()
