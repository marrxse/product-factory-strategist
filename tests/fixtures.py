def make_good_project(root: Path, slug: str = "good") -> Path:
    run("new", slug, "--title", "Тест")
    project = root / "projects" / slug
    (project / "sources" / "data.csv").write_text("month,churn\n1,0.35\n", encoding="utf-8")
    run("evidence", "add", "--kind", "web", "--source", "https://example.org/report", "--locator", "раздел 2",
        "--quote", "удержание падает после пробного периода", "--quality", "B")
    run("evidence", "add", "--kind", "table", "--source", "sources/data.csv", "--locator", "строка 1",
        "--quote", "churn 0.35 в первый месяц", "--quality", "A")
    for name, text in OUTPUTS.items():
        (project / "outputs" / name).write_text(text, encoding="utf-8")
    for num in range(0, 7):
        run("stage", str(num), "start")
        run("stage", str(num), "done")
    return project


def rewrite(project: Path, name: str, old: str, new: str) -> None:
    path = project / "outputs" / name
    text = path.read_text(encoding="utf-8")
    assert old in text, f"в {name} нет фрагмента {old!r}"
    path.write_text(text.replace(old, new), encoding="utf-8")
